def get_pest_by_id(class_id: int) -> Optional[dict[str, Any]]:
    """Retrieve pest details by 0-based class ID (0..101)."""
    if 0 <= class_id < len(IP102_CLASSES):
        dataset_name = IP102_CLASSES[class_id]
        return get_pest_by_name(dataset_name, class_id=class_id)
    return None

def get_pest_by_name(dataset_name: str, class_id: Optional[int] = None) -> dict[str, Any]:
    """Retrieve pest details by exact dataset name."""
    meta = CATALOG_METADATA.get(dataset_name, {})
    if class_id is None:
        try:
            class_id = IP102_CLASSES.index(dataset_name)
        except ValueError:
            class_id = -1

    return {
        "class_id": class_id,
        "dataset_name": dataset_name,
        "common_name": meta.get("common_name") or dataset_name.replace("_", " ").title(),
        "group": meta.get("group") or "Agricultural Insect",
        "description": meta.get("description") or UNAVAILABLE,
        "symptoms": meta.get("symptoms") or UNAVAILABLE,
        "relevance": meta.get("relevance") or "Identified in the IP102 pest dataset.",
        "verified": meta.get("verified", False),
    }

def get_all_pests() -> List[dict[str, Any]]:
    """Retrieve the list of all 102 supported pests."""
    return [get_pest_by_name(name, idx) for idx, name in enumerate(IP102_CLASSES)]

def search_pests(query: str) -> List[dict[str, Any]]:
    """Search pests by name, common name, group, or symptoms."""
    q = query.lower().strip()
    if not q:
        return get_all_pests()
    results = []
    for idx, name in enumerate(IP102_CLASSES):
        entry = get_pest_by_name(name, idx)
        if (
            q in entry["common_name"].lower()
            or q in entry["dataset_name"].lower()
            or q in entry["group"].lower()
            or q in entry["description"].lower()
            or q in entry["symptoms"].lower()
        ):
            results.append(entry)
    return results


def get_pest_management_details(dataset_name_or_id: str | int, instance_count: int = 1) -> dict[str, Any]:
    """Retrieve detailed IPM management guidance, symptoms, and biology for a pest class."""
    from app.data.pest_management import get_pest_management_details as _get_pm
    return _get_pm(dataset_name_or_id, instance_count=instance_count)
